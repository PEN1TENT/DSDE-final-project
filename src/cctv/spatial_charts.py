    for r in cams:
        px, py = proj(float(r["latitude"]), float(r["longitude"]))
        px = max(mx + 10, min(mx + mw - 10, px))
        py = max(my + 10, min(my + mh - 10, py))
        traf = float(r["band_w_mean"])
        giz = float(r["gi_star_z"])
