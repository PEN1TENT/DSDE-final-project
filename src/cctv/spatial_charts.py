    s.append(_text(sx + 18, 108, "1. The Two Bangkoks (Simpson's Zone)", size=13, weight="bold"))
    s.append(_text(sx + 18, 134, f"Modern CBD / Arterial (n=71 cams):", size=11, fill=INK2))
    s.append(_text(sx + 18, 156, f"{mb['mean_total']:.2f} veh/frame  (95% CI {mb['ci_low']:.1f}–{mb['ci_high']:.1f})", size=14, weight="bold", fill=CRIMSON))
