    # Card 2: DBSCAN 4 Corridors
    s.append(_rect(sx, 278, sw, 212, fill=CARD_LIGHT, stroke=BORDER_LIGHT, sw=1.4, rx=10))
    s.append(_rect(sx, 278, 6, 212, fill=CORAL, rx=2))
    s.append(_text(sx + 18, 302, "2. Four DBSCAN Busy Corridors", size=13, weight="bold"))
    s.append(_text(sx + 18, 320, "eps = 2.0 km, minPts = 3 across 33 busy cams", size=10.5, fill=MUTED))
    for idx, cor in enumerate(clusters_json["dbscan"]["corridors"]):
        yy = 346 + idx * 35
        ccol = corridor_colors[idx % len(corridor_colors)]
        s.append(_circle(sx + 24, yy - 4, 5, fill=ccol))
        s.append(_text(sx + 36, yy, _trunc(cor["name"], 35), size=11, weight="bold"))
        s.append(_text(sx + 36, yy + 14, f"{cor['camera_count']} cams · mean {cor['mean_traffic']:.1f} · {cor['total_malls_500m']} malls · {cor['total_frozen_frames']} frozen", size=10, fill=INK2))

    # Card 3: Outer-Bangkok Blind Spots
    bs = clusters_json["outer_blind_spots"]
