def _esc(text: Any) -> str:
    return html.escape(str(text), quote=True)


def _trunc(text: Any, limit: int = 34) -> str:
    s = str(text or "").strip()
    if len(s) <= limit:
        return s
    return s[: limit - 1].rstrip() + "…"


def _svg_open(width: int, height: int, bg: str) -> list[str]:
    return [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}">',
        f'<style>text {{ font-family: {FONT_STACK}; }}</style>',
        f'<rect width="{width}" height="{height}" fill="{bg}" />',
    ]


def _text(
    x: float,
    y: float,
    txt: Any,
    size: int = 12,
    fill: str = INK,
    weight: str = "normal",
    anchor: str = "start",
    extra: str = "",
) -> str:
    return (
        f'<text x="{x:.1f}" y="{y:.1f}" font-size="{size}" fill="{fill}" '
        f'font-weight="{weight}" text-anchor="{anchor}" {extra}>{_esc(txt)}</text>'
    )


def _rect(
    x: float,
    y: float,
    w: float,
    h: float,
    fill: str = "none",
    stroke: str = "none",
    sw: float = 1.0,
    rx: float = 0.0,
    opacity: float = 1.0,
    extra: str = "",
) -> str:
    op = f' opacity="{opacity:.2f}"' if opacity < 1.0 else ""
    rx_attr = f' rx="{rx:.1f}"' if rx > 0 else ""
    st_attr = f' stroke="{stroke}" stroke-width="{sw}"' if stroke != "none" else ""
    return f'<rect x="{x:.1f}" y="{y:.1f}" width="{max(0.0, w):.1f}" height="{max(0.0, h):.1f}" fill="{fill}"{st_attr}{rx_attr}{op} {extra}/>'


def _line(
    x1: float,
    y1: float,
    x2: float,
    y2: float,
    stroke: str = BORDER_LIGHT,
    sw: float = 1.0,
    dash: str = "",
    opacity: float = 1.0,
) -> str:
    da = f' stroke-dasharray="{dash}"' if dash else ""
    op = f' opacity="{opacity:.2f}"' if opacity < 1.0 else ""
    return f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="{stroke}" stroke-width="{sw}"{da}{op}/>'


def _circle(
    cx: float,
    cy: float,
    r: float,
    fill: str,
    stroke: str = "none",
    sw: float = 1.0,
    opacity: float = 1.0,
) -> str:
    op = f' opacity="{opacity:.2f}"' if opacity < 1.0 else ""
    st = f' stroke="{stroke}" stroke-width="{sw}"' if stroke != "none" else ""
    return f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{r:.1f}" fill="{fill}"{st}{op}/>'


def _write_and_validate(out_path: Path, lines: list[str]) -> None:
    lines.append("</svg>")
    xml_text = "\n".join(lines)
    ET.fromstring(xml_text)
    out_path.write_text(xml_text, encoding="utf-8")


def _gi_color(z: float) -> str:
    if z >= 1.96:
        return CRIMSON
    if z >= 1.2:
        return "#f87171"
    if z <= -1.96:
        return BLUE
    if z <= -1.2:
        return "#60a5fa"
    return "#94a3b8"


def _convex_hull(pts: list[tuple[float, float]]) -> list[tuple[float, float]]:
    """Monotone chain convex hull for small point sets."""
    pts = sorted(set(pts))
    if len(pts) <= 2:
        return pts

    def cross(o: tuple[float, float], a: tuple[float, float], b: tuple[float, float]) -> float:
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    lower: list[tuple[float, float]] = []
    for p in pts:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
            lower.pop()
        lower.append(p)
    upper: list[tuple[float, float]] = []
    for p in reversed(pts):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
            upper.pop()
        upper.append(p)
    return lower[:-1] + upper[:-1]


