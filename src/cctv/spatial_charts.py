    # Coordinate frame covering Bangkok metropolitan view (100.37..100.66, 13.68..13.845)
    lon0, lon1 = 100.38, 100.655
    lat0, lat1 = 13.685, 13.842

    def proj(lat: float, lon: float) -> tuple[float, float]:
        px = mx + (lon - lon0) / (lon1 - lon0) * mw
        py = my + (lat1 - lat) / (lat1 - lat0) * mh
        return px, py

    # Gaussian KDE soft heatmap tiles inside map frame
    kde = clusters_json.get("kde_grid", [])
    cell_w = mw / ((lon1 - lon0) / 0.013)
    cell_h = mh / ((lat1 - lat0) / 0.0103)
    for cell in kde:
        lat, lon, val = cell["lat"], cell["lon"], cell["traf_kde_norm"]
        if val < 0.08 or not (lat0 <= lat <= lat1 and lon0 <= lon <= lon1):
            continue
        cx, cy = proj(lat, lon)
        if val >= 0.7:
            col, op = "#dc2626", 0.16
        elif val >= 0.45:
            col, op = "#f97316", 0.12
        elif val >= 0.22:
            col, op = "#facc15", 0.09
        else:
            col, op = "#93c5fd", 0.06
        s.append(_rect(cx - cell_w / 2, cy - cell_h / 2, cell_w + 1, cell_h + 1, fill=col, opacity=op))

    # Latitude/Longitude subtle grid
    for g_lon in (100.40, 100.45, 100.50, 100.55, 100.60, 100.65):
        gx, _ = proj(lat0, g_lon)
        s.append(_line(gx, my, gx, my + mh, stroke="#e2e8f0", sw=1, dash="3,3"))
        s.append(_text(gx, my + mh + 16, f"{g_lon:.2f}°E", size=10, fill=MUTED, anchor="middle"))
    for g_lat in (13.70, 13.74, 13.78, 13.82):
        _, gy = proj(g_lat, lon0)
        s.append(_line(mx, gy, mx + mw, gy, stroke="#e2e8f0", sw=1, dash="3,3"))
        s.append(_text(mx + 6, gy - 4, f"{g_lat:.2f}°N", size=10, fill=MUTED))

    # Schematic Chao Phraya River polyline (North -> Rattanakosin bend -> Bang Kho Laem -> South)
    river_pts = [
        (13.835, 100.514),
        (13.800, 100.516),
        (13.775, 100.502),
        (13.758, 100.491),
        (13.744, 100.492),
        (13.729, 100.512),
        (13.704, 100.502),
        (13.688, 100.534),
    ]
    r_str = " ".join(f"{proj(la, lo)[0]:.1f},{proj(la, lo)[1]:.1f}" for la, lo in river_pts)
    s.append(f'<polyline points="{r_str}" fill="none" stroke="{RIVER_BLUE}" stroke-width="9" stroke-linecap="round" stroke-linejoin="round" opacity="0.65" />')
    rx_lbl, ry_lbl = proj(13.715, 100.506)
    s.append(_text(rx_lbl + 12, ry_lbl + 4, "Chao Phraya River", size=10, fill="#1d4ed8", weight="bold"))

    # Old City Rattanakosin-Dusit zone highlight box
    ox1, oy1 = proj(13.790, 100.490)
    ox2, oy2 = proj(13.735, 100.525)
    s.append(_rect(ox1, oy1, ox2 - ox1, oy2 - oy1, fill="#dbeafe", stroke=BLUE, sw=1.5, rx=8, opacity=0.22))
