def generate_all(in_dir: Path, out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    with (in_dir / "camera_spatial_profile.csv").open(encoding="utf-8", newline="") as f:
        cams = list(csv.DictReader(f))
    clusters_json = json.loads((in_dir / "spatial_clusters_and_blindspots.json").read_text(encoding="utf-8"))
    summary = json.loads((in_dir / "insights_summary.json").read_text(encoding="utf-8"))

    targets = [
        out_dir / "01_two_bangkoks_hotspots_map.svg",
        out_dir / "02_intersection_compound_friction.svg",
        out_dir / "03_weekend_immunity_and_modal_shift.svg",
        out_dir / "04_multivariate_drivers_and_ai_blindspots.svg",
        out_dir / "05_camera_health_paradox_and_next10.svg",
        out_dir / "06_executive_infographic.svg",
    ]
    build_chart_01_map(cams, clusters_json, summary, targets[0])
    build_chart_02_intersections(summary, targets[1])
    build_chart_03_weekend_modal(summary, targets[2])
    build_chart_04_drivers_blindspots(summary, targets[3])
    build_chart_05_health_and_policy(summary, targets[4])
    build_chart_06_infographic(cams, clusters_json, summary, targets[5])

    pulse_path = in_dir / "spatio_temporal_pulse.json"
    if pulse_path.exists():
        pulse = json.loads(pulse_path.read_text(encoding="utf-8"))
        p7 = out_dir / "07_bangkok_daily_pulse_by_district.svg"
        build_chart_07_daily_pulse(pulse, p7)
        targets.append(p7)
    return targets


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--in-dir", type=Path, default=Path("reports/insights"))
    parser.add_argument("--out-dir", type=Path, default=Path("reports/figures/spatial_insights"))
    args = parser.parse_args()
    paths = generate_all(args.in_dir, args.out_dir)
    for p in paths:
        print(f"wrote {p} ({p.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
