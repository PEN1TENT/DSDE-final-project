def build_chart_02_intersections(summary: dict[str, Any], out_path: Path) -> None:
    """02: Intersection Topology & 2x2 Compound Friction Matrix."""
    W, H = 1240, 620
    s = _svg_open(W, H, BG_LIGHT)

    inter = summary["intersections"]
    comp = summary["compound_friction_2x2"]
    c_iso = next(x for x in comp if "Mid-block, No" in x["segment"])
    c_hot = next(x for x in comp if "Intersection + Mall" in x["segment"])
    lift_pct = 100.0 * (c_hot["mean_total"] - c_iso["mean_total"]) / c_iso["mean_total"]

    s.append(_text(36, 40, f"Compound Friction: Intersections Near Malls/Rail Hit {c_hot['busy_pct']:.0f}% Busy vs 0% at Isolated Mid-Blocks", size=21, weight="bold"))
    s.append(_text(36, 63, f"Stratified golden counts (n = 891 frames, 100 cameras); 5+-way mega-interchanges average {inter[-1]['mean_total']:.1f} vehicles/frame (+{lift_pct:.0f}% Compound Friction)", size=13, fill=INK2))

    # Left Panel: Junction Topology Stacked Modal Bars + 95% CI
    px, py, pw, ph = 36, 92, 590, 480
    s.append(_rect(px, py, pw, ph, fill=CARD_LIGHT, stroke=BORDER_LIGHT, sw=1.4, rx=10))
    s.append(_text(px + 20, py + 28, "A. Vehicle Count & Modal Mix by Intersection Geometry", size=15, weight="bold"))
    s.append(_text(px + 20, py + 47, "Mean vehicles/frame with 95% bootstrap CI on total (n = 2,000 draws)", size=11, fill=MUTED))

    cx0, cy0, cw, ch = px + 66, py + 80, pw - 96, 300
    max_y = 24.0
    # Y-axis gridlines
    for yv in (0, 5, 10, 15, 20):
        yy = cy0 + ch - (yv / max_y) * ch
        s.append(_line(cx0, yy, cx0 + cw, yy, stroke="#e5e7eb", sw=1))
        s.append(_text(cx0 - 8, yy + 4, str(yv), size=11, fill=MUTED, anchor="end"))
    s.append(_text(px + 22, cy0 + ch / 2, "Vehicles / frame", size=11, fill=INK2, anchor="middle", extra=f'transform="rotate(-90 {px+22:.1f} {cy0+ch/2:.1f})"'))

    bw = 68
    step = cw / len(inter)
    for i, row in enumerate(inter):
        bx = cx0 + step * (i + 0.5) - bw / 2
        y_base = cy0 + ch
        car_h = (row["mean_car"] / max_y) * ch
        moto_h = (row["mean_motorcycle"] / max_y) * ch
        heavy_val = row["mean_bus"] + row["mean_truck"]
        heavy_h = (heavy_val / max_y) * ch

        # Car
        s.append(_rect(bx, y_base - car_h, bw, car_h, fill=BLUE))
        # Motorcycle
        s.append(_rect(bx, y_base - car_h - moto_h, bw, moto_h, fill=ORANGE))
        # Bus/Truck
        s.append(_rect(bx, y_base - car_h - moto_h - heavy_h, bw, heavy_h, fill=TEAL))

        # 95% CI Whisker on Total
        ci_lo_y = y_base - (row["ci_low"] / max_y) * ch
        ci_hi_y = y_base - (row["ci_high"] / max_y) * ch
        mid_x = bx + bw / 2
        s.append(_line(mid_x, ci_lo_y, mid_x, ci_hi_y, stroke=INK, sw=1.8))
        s.append(_line(mid_x - 7, ci_lo_y, mid_x + 7, ci_lo_y, stroke=INK, sw=1.8))
        s.append(_line(mid_x - 7, ci_hi_y, mid_x + 7, ci_hi_y, stroke=INK, sw=1.8))

        s.append(_text(mid_x, ci_hi_y - 8, f"{row['mean_total']:.2f}", size=13, weight="bold", anchor="middle"))
